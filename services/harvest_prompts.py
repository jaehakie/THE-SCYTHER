# ── 7. 끝에서 반복하는 핵심 규칙 (긴 대화에서도 말투가 풀리지 않게) ───────
TAIL = "※ 다시 확인: 캐릭터 유지 · 1~3문장 대사만 · 의혹의 진실 확정 금지 · 결말 대신 말하기 금지."


def build_system(who: str, scene: Optional[str], state: Optional[dict], options: Optional[list] = None) -> str:
    ex = "\n".join(f"플레이어: {q}\n{who}: {a}" for q, a in EXAMPLES[who])
    blocks = [
        COMMON,
        PERSONA[who],
        SCENE.get(scene or "", ""),
        describe_state(state or {}),
        f"[말투 예시 — 문장을 그대로 베끼지 말고 결을 따른다]\n{ex}",
    ]
    if options:
        opts = "\n".join(f"{i + 1}. {o}" for i, o in enumerate(options))
        blocks += [CLASSIFY.format(options=opts), CLASSIFY_HINT.get(scene or "", "")]
    blocks.append(TAIL)
    return "\n\n".join(b for b in blocks if b)
